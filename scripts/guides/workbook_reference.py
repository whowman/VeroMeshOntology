"""Write docs/guides/workbook-reference.md: every sheet and column of the VeroMesh model workbook.

    python scripts/guides/workbook_reference.py           # rewrite the reference
    python scripts/guides/workbook_reference.py --check   # exit 1 if it is out of date

The workbook is the standard format in which an organization gives VeroMesh its
model (the template comes from `veromesh-connect spreadsheet template`). This
reference is generated from the API's schema snapshot
(tests/contracts/golden/api-schema.json, kept current by the contract tests), so the
guide always says exactly what VeroMesh accepts. Never edit the Markdown by hand:
change the help text in service/src/veromesh/entities.py and regenerate.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SCHEMA = ROOT / "tests" / "contracts" / "golden" / "api-schema.json"
OUT = ROOT / "docs" / "guides" / "workbook-reference.md"

# Which sheets each team usually fills in, in the order to fill them.
PACKS = [
    (
        "Organization",
        "who does what: usually from HR and the operating model",
        ["objectives", "kpis", "capabilities", "processes", "roles", "people"],
    ),
    (
        "Governance",
        "who may decide what, and which AI uses are approved: usually from finance, risk and the AI board",
        ["policies", "actions", "impacts", "authorities", "co-approvals", "agents", "ai-use-cases"],
    ),
    (
        "Systems and data",
        "where the work and its data live: usually from IT and the data office",
        ["systems", "data-products", "data-elements", "column-bindings"],
    ),
]
KINDS = {
    "id": "ID",
    "label": "text",
    "text": "text",
    "decimal": "number",
    "date": "date (YYYY-MM-DD)",
    "bool": "yes or no",
    "duration": "duration (ISO 8601, e.g. P7Y)",
}


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def render(schema: list[dict]) -> str:
    by_type = {t["type"]: t for t in schema}
    labels = {t["type"]: t["label"] for t in schema}
    placed = {t for _, _, ts in PACKS for t in ts}
    packs = PACKS + (
        [("Other", "", [t for t in by_type if t not in placed])] if set(by_type) - placed else []
    )
    out = [
        "---",
        "title: VeroMesh Model Workbook — Reference",
        "---",
        "",
        "<!-- Generated by scripts/guides/workbook_reference.py from the API schema. Do not edit. -->",
        "",
        "# About this reference",
        "",
        "Every sheet and column of the VeroMesh model workbook, the standard format in which an organization"
        " gives VeroMesh its model. How to fill it in and load it is in the **User Guide**"
        ' ("Maintaining the model in the workbook"). This reference is generated from the schema VeroMesh'
        " validates against, so it always matches what VeroMesh accepts.",
        "",
        "Conventions, on every sheet:",
        "",
        "- **ID** is a short key, unique across the whole model: letters, digits, `.`, `_` or `-`."
        " Other sheets refer to a row by its ID.",
        "- **Required** columns must be filled on every row; the template shows them in dark blue.",
        "- Several values in one cell are separated by `;`.",
        "- A reference may point at a row on another sheet, in another workbook, or already in VeroMesh"
        " from another source.",
        "- Dates are `YYYY-MM-DD`; amounts are plain numbers in the currency stated.",
        "",
    ]
    for pack, who, types in packs:
        out += [f"# {pack} sheets", ""]
        if who:
            out += [f"The {pack.lower()} sheets record {who}.", ""]
        for t in types:
            if t not in by_type:
                continue
            s = by_type[t]
            out += [f"## {s['label']}", "", s["help"]]
            if not s["keyed"]:
                out[-1] += " Rows have no ID of their own: each belongs to the row it names."
            out += ["", "| Column | Required | Holds | What it means |", "| --- | --- | --- | --- |"]
            for f in s["fields"]:
                if f["key"] == "id" and not s["keyed"]:
                    continue
                if f["kind"] == "ref":
                    holds = "ID of " + " or ".join(labels[x] for x in f.get("targets", []))
                elif f.get("values"):
                    holds = "one of: " + ", ".join(f"`{v}`" for v in f["values"])
                elif f["kind"] == "class":
                    holds = "a type"
                else:
                    holds = KINDS.get(f["kind"], f["kind"])
                if f.get("multi"):
                    holds += " (several, separated by `;`)"
                if f["key"] == "id":
                    out.append("| ID | yes | ID | Unique key for this row (see the conventions above). |")
                    continue
                notes = f["help"].replace(" Separate several with ';'.", "") + (
                    " Personal: shown only to those who need it." if f.get("personal") else ""
                )
                out.append(
                    f"| {_cell(f['label'])} | {'yes' if f['required'] else ''} | {_cell(holds)} | {_cell(notes)} |"
                )
            out.append("")
    return "\n".join(out).rstrip() + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="exit 1 if the reference is out of date")
    a = ap.parse_args(argv)
    text = render(json.loads(SCHEMA.read_text()))
    if a.check:
        if not OUT.exists() or OUT.read_text() != text:
            print(f"{OUT.relative_to(ROOT)} is out of date: run python scripts/guides/workbook_reference.py")
            return 1
        print(f"{OUT.relative_to(ROOT)} is current")
        return 0
    OUT.write_text(text)
    print(OUT.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
